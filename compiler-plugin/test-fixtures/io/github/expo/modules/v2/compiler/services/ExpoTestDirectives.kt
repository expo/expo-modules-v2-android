package io.github.expo.modules.v2.compiler.services

import org.jetbrains.kotlin.test.directives.model.SimpleDirectivesContainer

/**
 * Directives this project's tests understand on top of the stock ones.
 *
 * Box tests dump nothing by default: `box()` is where behaviour is checked, and a dump is a change
 * detector reviewers have to read on every change to the plugin. A test whose point is the shape of
 * the generated code opts in with `// DUMP_GENERATED`.
 *
 * The stock `// FIR_DUMP`, `// DUMP_IR` and `// DUMP_KT_IR` still work for looking at a compilation
 * locally, but their output is not committed: unlike `*.generated.kt.txt` it would be compared on
 * every Kotlin release, and each release prints the trees a little differently.
 */
object ExpoTestDirectives : SimpleDirectivesContainer() {
  val DUMP_GENERATED by directive(
    "Dump the declarations the plugin generated, as Kotlin-like source, into `*.generated.kt.txt`",
  )
}

/**
 * Whether this run compares (and, with `-PupdateTestData`, writes) the committed `*.generated.kt.txt`
 * dumps. Only the catalog's Kotlin does - see `dumpKotlinVersion` in compiler-plugin/build.gradle.kts.
 * Every other release still compiles and runs the same tests.
 */
val compareDumps: Boolean = System.getProperty("expoModules.compareDumps")?.toBooleanStrictOrNull() ?: true
