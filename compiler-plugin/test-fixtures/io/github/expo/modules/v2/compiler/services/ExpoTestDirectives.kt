package io.github.expo.modules.v2.compiler.services

import org.jetbrains.kotlin.test.directives.model.SimpleDirectivesContainer

/**
 * Directives this project's tests understand on top of the stock ones.
 *
 * No test dumps anything: `box()` and the diagnostics in the test files are what is checked, on every
 * supported Kotlin release. To look at what the plugin generated for a test, add `// DUMP_GENERATED`
 * (or the stock `// DUMP_KT_IR`, `// DUMP_IR`, `// FIR_DUMP`) to it and run it: the first run writes
 * the dump next to the test and fails. Remove the directive afterwards; the next run fails once more
 * and deletes the dump. Dumps are not committed - every Kotlin release prints them a little
 * differently.
 */
object ExpoTestDirectives : SimpleDirectivesContainer() {
  val DUMP_GENERATED by directive(
    "Dump the declarations the plugin generated, as Kotlin-like source, into `*.generated.kt.txt`",
  )

  val EXPO_PACKAGE_NAME by stringDirective(
    "The package of this module's output. A module that depends on it gets a `classpathPackage` " +
      "option for the output, the way an app's build maps each module library to its npm package",
  )
}
